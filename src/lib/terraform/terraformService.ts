const BASE_WORKSPACE_DIR = path.resolve(process.cwd(), 'terraform-workspaces');

// Ensure base workspaces directory exists
if (!fs.existsSync(BASE_WORKSPACE_DIR)) {
  fs.mkdirSync(BASE_WORKSPACE_DIR, { recursive: true });
}

/**
 * Redact sensitive strings (AWS Secret Keys, Azure client secrets, private keys, password)
 */
export function redactSecrets(text: string, knownSecrets: string[] = []): string {
  if (!text) return '';
  let sanitized = text;

  // Mask known secret values
  for (const s of knownSecrets) {
    if (s && s.length >= 4) {
      const escaped = s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      sanitized = sanitized.replace(new RegExp(escaped, 'g'), '********');
    }
  }

  // Generic patterns
  sanitized = sanitized.replace(/aws_secret_access_key\s*=\s*["'][^"']+["']/gi, 'aws_secret_access_key = "********"');
  sanitized = sanitized.replace(/client_secret\s*=\s*["'][^"']+["']/gi, 'client_secret = "********"');
  sanitized = sanitized.replace(/ARM_CLIENT_SECRET=[^\s]+/gi, 'ARM_CLIENT_SECRET=********');
  sanitized = sanitized.replace(/AWS_SECRET_ACCESS_KEY=[^\s]+/gi, 'AWS_SECRET_ACCESS_KEY=********');
  sanitized = sanitized.replace(/-----BEGIN [A-Z ]+PRIVATE KEY-----[\s\S]+?-----END [A-Z ]+PRIVATE KEY-----/g, '-----BEGIN PRIVATE KEY-----\n[REDACTED PRIVATE KEY]\n-----END PRIVATE KEY-----');

  return sanitized;
}

/**
 * Get the isolated directory for a project and workspace
 */
export function getWorkspaceDir(projectId: string, workspace = 'default'): string {
  const dir = path.join(BASE_WORKSPACE_DIR, projectId.toString(), workspace);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  return dir;
}

/**
 * Write all project files to the target workspace directory
 */
export async function syncProjectFilesToDisk(
  project: ITerraformProject,
  workspace = 'default'
): Promise<string> {
  const dir = getWorkspaceDir(project._id.toString(), workspace);

  // If project has no files yet, write default boilerplate
  if (!project.files || project.files.length === 0) {
    const defaultMainTf = `# ==============================================================================
# Terraform Infrastructure Configuration
# Project: ${project.name}
# Provider: ${project.provider.toUpperCase()} | Environment: ${project.environment}
# ==============================================================================

terraform {
  required_version = ">= 1.5.0"
  required_providers {
    ${
      project.provider === 'aws'
        ? `aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }`
        : `azurerm = {
      source  = "hashicorp/azurerm"
      version = "~> 3.0"
    }`
    }
  }
}

provider "${project.provider === 'aws' ? 'aws' : 'azurerm'}" {
  ${
    project.provider === 'aws'
      ? `region = "${project.region || 'us-east-1'}"`
      : `features {}`
  }
}
`;
    fs.writeFileSync(path.join(dir, 'main.tf'), defaultMainTf, 'utf8');
  } else {
    for (const f of project.files) {
      if (f.name && f.content !== undefined) {
        fs.writeFileSync(path.join(dir, f.name), f.content, 'utf8');
      }
    }
  }

  // Load project & workspace variables to generate terraform.tfvars if needed
  const vars = await TerraformVariable.find({
    projectId: project._id,
    $or: [{ workspace: 'all' }, { workspace }],
    category: 'terraform',
  }).lean();

  if (vars.length > 0) {
    let tfvarsContent = `# Auto-generated by Multi-Cloud Monitoring Terraform Automation\n`;
    for (const v of vars) {
      if (v.type === 'number' || v.type === 'boolean') {
        tfvarsContent += `${v.key} = ${v.value}\n`;
      } else if (v.type === 'list' || v.type === 'map') {
        tfvarsContent += `${v.key} = ${v.value}\n`;
      } else {
        tfvarsContent += `${v.key} = "${v.value}"\n`;
      }
    }
    fs.writeFileSync(path.join(dir, 'terraform.tfvars'), tfvarsContent, 'utf8');
  }

  return dir;
}

/**
 * Build execution environment variables including cloud credentials
 */
export async function buildExecutionEnv(
  project: ITerraformProject,
  workspace = 'default'
): Promise<{ env: NodeJS.ProcessEnv; secrets: string[] }> {
  const env: NodeJS.ProcessEnv = {
    ...process.env,
    TF_IN_AUTOMATION: '1',
    TF_INPUT: '0',
  };
  const secrets: string[] = [];

  // Check if project has an associated CloudAccount
  if (project.cloudAccountId) {
    try {
      const cloudAccount = await CloudAccount.findById(project.cloudAccountId)
        .select('+accessKeyId +secretAccessKey +clientId +clientSecret')
        .lean();

      if (cloudAccount) {
        if (project.provider === 'aws') {
          if (cloudAccount.accessKeyId) {
            env.AWS_ACCESS_KEY_ID = cloudAccount.accessKeyId;
          }
          if (cloudAccount.secretAccessKey) {
            env.AWS_SECRET_ACCESS_KEY = cloudAccount.secretAccessKey;
            secrets.push(cloudAccount.secretAccessKey);
          }
          env.AWS_DEFAULT_REGION = project.region || 'us-east-1';
        } else if (project.provider === 'azure') {
          if (cloudAccount.clientId) env.ARM_CLIENT_ID = cloudAccount.clientId;
          if (cloudAccount.clientSecret) {
            env.ARM_CLIENT_SECRET = cloudAccount.clientSecret;
            secrets.push(cloudAccount.clientSecret);
          }
          if (cloudAccount.subscriptionId) env.ARM_SUBSCRIPTION_ID = cloudAccount.subscriptionId;
          if (cloudAccount.tenantId) env.ARM_TENANT_ID = cloudAccount.tenantId;
        }
      }
    } catch (e) {
      console.warn('Failed to load cloud account credentials:', e);
    }
  }

  // Load custom environment variables configured in TerraformVariable
  const envVars = await TerraformVariable.find({
    projectId: project._id,
    $or: [{ workspace: 'all' }, { workspace }],
    category: 'env',
  }).lean();

  for (const ev of envVars) {
    env[ev.key] = ev.value;
    if (ev.sensitive) {
      secrets.push(ev.value);
    }
  }

  return { env, secrets };
}

export interface ExecutionResult {
  success: boolean;
  exitCode: number;
  stdout: string;
  stderr: string;
  rawLogs: string;
  durationMs: number;
  planSummary?: {
    toAdd: number;
    toChange: number;
    toDestroy: number;
    toReplace: number;
  };
  resourceChanges?: Array<{
    action: 'create' | 'update' | 'delete' | 'replace' | 'no-op';
    address: string;
    type: string;
    name: string;
  }>;
  outputs?: Record<string, { value: any; sensitive: boolean; type?: string }>;
}

/**
 * Execute a real Terraform CLI command in the project's workspace directory
 */
export async function executeLocalTerraform(
  project: ITerraformProject,
  workspace: string,
  args: string[],
  timeoutMs = 300000
): Promise<ExecutionResult> {
  const dir = await syncProjectFilesToDisk(project, workspace);
  const { env, secrets } = await buildExecutionEnv(project, workspace);

  const startTime = Date.now();

  return new Promise((resolve) => {
    let stdout = '';
    let stderr = '';

    const child = spawn('terraform', args, {
      cwd: dir,
      env,
      shell: true,
    });

    const timer = setTimeout(() => {
      child.kill('SIGTERM');
      const durationMs = Date.now() - startTime;
      resolve({
        success: false,
        exitCode: 124,
        stdout,
        stderr: stderr + `\n[TIMEOUT] Command timed out after ${timeoutMs / 1000}s`,
        rawLogs: redactSecrets(stdout + '\n' + stderr, secrets),
        durationMs,
      });
    }, timeoutMs);

    child.stdout.on('data', (data) => {
      stdout += data.toString();
    });

    child.stderr.on('data', (data) => {
      stderr += data.toString();
    });

    child.on('close', (code) => {
      clearTimeout(timer);
      const durationMs = Date.now() - startTime;
      const cleanStdout = redactSecrets(stdout, secrets);
      const cleanStderr = redactSecrets(stderr, secrets);
      const rawLogs = cleanStdout + (cleanStderr ? `\n--- ERRORS ---\n${cleanStderr}` : '');

      // Parse plan counts if present (e.g. Plan: 3 to add, 1 to change, 0 to destroy.)
      let planSummary: { toAdd: number; toChange: number; toDestroy: number; toReplace: number } | undefined;
      const planMatch = rawLogs.match(/Plan:\s*(\d+)\s*to add,\s*(\d+)\s*to change,\s*(\d+)\s*to destroy/i);
      if (planMatch) {
        planSummary = {
          toAdd: parseInt(planMatch[1], 10),
          toChange: parseInt(planMatch[2], 10),
          toDestroy: parseInt(planMatch[3], 10),
          toReplace: 0,
        };
      }

      // Check for zero changes
      if (rawLogs.includes('No changes. Your infrastructure matches the configuration.')) {
        planSummary = { toAdd: 0, toChange: 0, toDestroy: 0, toReplace: 0 };
      }

      // Parse resource change lines (# aws_instance.web will be created, etc.)
      const resourceChanges: Array<{
        action: 'create' | 'update' | 'delete' | 'replace' | 'no-op';
        address: string;
        type: string;
        name: string;
      }> = [];

      const changeRegex = /#\s+([a-zA-Z0-9_\-\.]+)\s+will be\s+(created|updated in-place|destroyed|replaced)/g;
      let match;
      while ((match = changeRegex.exec(rawLogs)) !== null) {
        const address = match[1];
        const actionStr = match[2];
        const parts = address.split('.');
        const type = parts[0] || 'resource';
        const name = parts[1] || address;

        let action: 'create' | 'update' | 'delete' | 'replace' = 'create';
        if (actionStr.includes('create')) action = 'create';
        else if (actionStr.includes('update')) action = 'update';
        else if (actionStr.includes('destroy')) action = 'delete';
        else if (actionStr.includes('replace')) action = 'replace';

        resourceChanges.push({ action, address, type, name });
      }

      resolve({
        success: code === 0,
        exitCode: code ?? 1,
        stdout: cleanStdout,
        stderr: cleanStderr,
        rawLogs,
        durationMs,
        planSummary,
        resourceChanges,
      });
    });

    child.on('error', (err) => {
      clearTimeout(timer);
      const durationMs = Date.now() - startTime;
      resolve({
        success: false,
        exitCode: 1,
        stdout,
        stderr: err.message,
        rawLogs: `Terraform execution error: ${err.message}`,
        durationMs,
      });
    });
  });
}

/**
 * Check if Terraform is installed on a registered Linux server via SSH
 */
export async function checkServerTerraform(server: any): Promise<{
  installed: boolean;
  version?: string;
  binaryPath?: string;
  error?: string;
}> {
  return new Promise((resolve) => {
    try {
      const client = new Client();
      const config = buildSSHConfig(server, 8000);

      client.on('ready', () => {
        client.exec('which terraform && terraform -version', (err, stream) => {
          if (err) {
            client.end();
            resolve({ installed: false, error: err.message });
            return;
          }

          let out = '';
          stream.on('data', (d: Buffer) => {
            out += d.toString();
          });

          stream.on('close', (code: number) => {
            client.end();
            if (code === 0 && out.includes('Terraform v')) {
              const lines = out.split('\n');
              const binaryPath = lines[0]?.trim();
              const versionLine = lines.find((l) => l.includes('Terraform v')) || 'Terraform v1.0';
              const version = versionLine.split(' ')[1] || 'v1.0';
              resolve({ installed: true, version, binaryPath });
            } else {
              resolve({ installed: false, error: 'Terraform binary not found in PATH' });
            }
          });
        });
      });

      client.on('error', (err) => {
        resolve({ installed: false, error: err.message });
      });

      client.connect(config);
    } catch (e: any) {
      resolve({ installed: false, error: e.message });
    }
  });
}

/**
 * Install official Terraform on an authorized registered Linux server via SSH
 */
export async function installServerTerraform(server: any): Promise<{
  success: boolean;
  logs: string;
  version?: string;
  error?: string;
}> {
  return new Promise((resolve) => {
    try {
      const client = new Client();
      const config = buildSSHConfig(server, 20000);

      client.on('ready', () => {
        // Official HashiCorp Debian/Ubuntu installation script
        const installCmd = `
export DEBIAN_FRONTEND=noninteractive
sudo apt-get update -y && \
sudo apt-get install -y gnupg software-properties-common curl lsb-release && \
curl -fsSL https://apt.releases.hashicorp.com/gpg | sudo gpg --dearmor -o /usr/share/keyrings/hashicorp-archive-keyring.gpg --yes && \
echo "deb [signed-by=/usr/share/keyrings/hashicorp-archive-keyring.gpg] https://apt.releases.hashicorp.com $(lsb_release -cs) main" | sudo tee /etc/apt/sources.list.d/hashicorp.list && \
sudo apt-get update -y && \
sudo apt-get install -y terraform && \
terraform -version
        `;

        client.exec(installCmd, (err, stream) => {
          if (err) {
            client.end();
            resolve({ success: false, logs: '', error: err.message });
            return;
          }

          let logs = '';
          stream.on('data', (d: Buffer) => {
            logs += d.toString();
          });
          stream.stderr.on('data', (d: Buffer) => {
            logs += d.toString();
          });

          stream.on('close', (code: number) => {
            client.end();
            const success = code === 0 && logs.includes('Terraform v');
            const versionMatch = logs.match(/Terraform v([0-9\.]+)/);
            resolve({
              success,
              logs,
              version: versionMatch ? versionMatch[1] : undefined,
              error: success ? undefined : `Installation exited with code ${code}`,
            });
          });
        });
      });

      client.on('error', (err) => {
        resolve({ success: false, logs: '', error: err.message });
      });

      client.connect(config);
    } catch (e: any) {
      resolve({ success: false, logs: '', error: e.message });
    }
  });
}

/**
 * Uninstall Terraform from a registered server via SSH
 */
export async function uninstallServerTerraform(server: any): Promise<{
  success: boolean;
  logs: string;
  error?: string;
}> {
  return new Promise((resolve) => {
    try {
      const client = new Client();
      const config = buildSSHConfig(server, 15000);

      client.on('ready', () => {
        const cmd = 'sudo apt-get remove -y terraform && sudo rm -f /etc/apt/sources.list.d/hashicorp.list';
        client.exec(cmd, (err, stream) => {
          if (err) {
            client.end();
            resolve({ success: false, logs: '', error: err.message });
            return;
          }

          let logs = '';
          stream.on('data', (d: Buffer) => {
            logs += d.toString();
          });
          stream.on('close', (code: number) => {
            client.end();
            resolve({
              success: code === 0,
              logs,
              error: code === 0 ? undefined : `Uninstall failed with code ${code}`,
            });
          });
        });
      });

      client.on('error', (err) => {
        resolve({ success: false, logs: '', error: err.message });
      });

      client.connect(config);
    } catch (e: any) {
      resolve({ success: false, logs: '', error: e.message });
    }
  });
}
